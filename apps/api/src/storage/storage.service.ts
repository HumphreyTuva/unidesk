import { Injectable, NotFoundException } from '@nestjs/common';
import { mkdir, readFile, stat, writeFile } from 'fs/promises';
import { createReadStream } from 'fs';
import { dirname, join, resolve } from 'path';
import type { Readable } from 'stream';

export type StoredFile = { stream: Readable; size?: number };

// Files are PRIVATE: they are only ever streamed through the API after an access check, never linked directly.
//   STORAGE_DRIVER=local (default): saved in apps/api/uploads. For testing on your computer.
//   STORAGE_DRIVER=s3: Cloudflare R2 or any S3-compatible bucket (S3_ENDPOINT, S3_BUCKET, S3_ACCESS_KEY, S3_SECRET_KEY).
@Injectable()
export class StorageService {
  private get driver() { return process.env.STORAGE_DRIVER === 's3' ? 's3' : 'local'; }
  private get root() { return resolve(process.cwd(), process.env.UPLOAD_DIR || 'uploads'); }

  private s3Cache: any;
  private async s3() {
    if (!this.s3Cache) {
      const { S3Client } = await import('@aws-sdk/client-s3');
      this.s3Cache = new S3Client({
        region: 'auto',
        endpoint: process.env.S3_ENDPOINT,
        credentials: { accessKeyId: process.env.S3_ACCESS_KEY || '', secretAccessKey: process.env.S3_SECRET_KEY || '' },
      });
    }
    return this.s3Cache;
  }

  // Keys are generated by the server (papers/<uuid>.pdf), but we still refuse anything that could leave the folder.
  private localPath(key: string) {
    const p = resolve(this.root, key);
    if (!p.startsWith(this.root + '/') && !p.startsWith(this.root + '\\')) throw new NotFoundException();
    return p;
  }

  async put(key: string, body: Buffer, contentType: string) {
    if (this.driver === 's3') {
      const { PutObjectCommand } = await import('@aws-sdk/client-s3');
      await (await this.s3()).send(new PutObjectCommand({ Bucket: process.env.S3_BUCKET, Key: key, Body: body, ContentType: contentType }));
      return;
    }
    const path = this.localPath(key);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, body);
  }

  async get(key: string): Promise<StoredFile> {
    if (this.driver === 's3') {
      const { GetObjectCommand } = await import('@aws-sdk/client-s3');
      try {
        const r = await (await this.s3()).send(new GetObjectCommand({ Bucket: process.env.S3_BUCKET, Key: key }));
        return { stream: r.Body as Readable, size: r.ContentLength };
      } catch {
        throw new NotFoundException();
      }
    }
    const path = this.localPath(key);
    try {
      const s = await stat(path);
      return { stream: createReadStream(path), size: s.size };
    } catch {
      throw new NotFoundException();
    }
  }
}
